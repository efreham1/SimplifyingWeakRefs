#!/usr/bin/env bash
set -euo pipefail

# create_configs.sh
# Creates per-variant CONF directories using configure --with-conf-name
# and writes a variants mapping file at scripts/variants.conf
#
# patches/base/ contains common ref-proc source patches (shared by 8 variants).
# patches/<variant>/ contains variant-specific ref-proc files (3 files each).
# patches/weak_fields/ contains the weak field annotation/processing patches (standalone).
# The build script layers base + variant onto src/ for ref-proc configs,
# or applies only weak_fields/ for the weak_fields config.
#
# Usage:
#   ./scripts/create_configs.sh

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
OUT_CONF_FILE="${SCRIPT_DIR}/variants.conf"
debug_levels=("release" "fastdebug")

variants=(
  "none"
  "clear_path_only"
  "sep_only"
  "dyn_only"
  "clear_path_sep"
  "clear_path_dyn"
  "sep_dyn"
  "all"
  "weak_fields"
)

CONFIGS_DIR="${REPO_ROOT}/patches"

# Sanity check: base and sep_base directories must exist
for required_dir in base sep_base; do
  if [ ! -d "${CONFIGS_DIR}/${required_dir}" ]; then
    echo "Error: missing config directory: ${CONFIGS_DIR}/${required_dir}" >&2
    exit 1
  fi
done
for name in "${variants[@]}"; do
  if [ "${name}" = "none" ]; then continue; fi
  if [ ! -d "${CONFIGS_DIR}/${name}" ]; then
    echo "Error: missing config directory: ${CONFIGS_DIR}/${name}" >&2
    exit 1
  fi
done

# Write header for mapping file
cat > "${OUT_CONF_FILE}" <<EOF
# conf_name|variant
# Auto-generated by scripts/create_configs.sh
EOF

for name in "${variants[@]}"; do
  for level in "${debug_levels[@]}"; do
    conf_name="${name}-linux-x86_64-server-${level}"

    echo
    echo "=== Preparing config: ${conf_name} ==="

    if [ ! -d "build/${conf_name}" ]; then
      echo "Running: bash configure --with-conf-name=${conf_name} --with-debug-level=${level}"
      bash configure --with-conf-name="${conf_name}" --with-debug-level="${level}"
    else
      echo "Skipping configure; build/${conf_name} already exists"
    fi

    # Save mapping: conf_name|variant
    printf "%s|%s\n" "${conf_name}" "${name}" >> "${OUT_CONF_FILE}"
  done
done

echo
echo "Wrote mapping to ${OUT_CONF_FILE}"
echo "Run scripts/build_configs.sh to build the prepared configurations."
